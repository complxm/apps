"""Candidate new bridges: Old/New Testament verse pairs that the evidence says belong together but no bridge covers yet.

Looks at every OpenBible.info cross-reference between an Old and a New Testament verse (either direction), and for each
pair measures the same things as build_evidence.py: reader votes, the longest run of identical BSB wording, and whether
the New Testament passage refers to Scripture nearby ("it is written", "to fulfill"...). Pairs already inside a bridge
are left out. The result is a list to read and choose from, not new bridges.

Usage: python3 scripts/find_candidates.py
Writes research/candidate_bridges.json and research/candidate_bridges.md
"""
import json
import math
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from build_evidence import BOOKS, BY_OSIS, D, ROOT, chapter, expand, formula_near, longest_run, parse_refs, words  # noqa: E402

OUT = os.path.join(ROOT, "research")
TESTAMENT = {b["osis"]: b["testament"] for b in BOOKS}
NAME = {b["osis"]: ("Psalm" if b["osis"] == "Ps" else b["name"]) for b in BOOKS}
MIN_VOTES = 10


def label(vs):
    (o, c, v), (o2, c2, v2) = vs[0], vs[-1]
    if (o, c) == (o2, c2):
        return f"{NAME[o]} {c}:{v}" + (f"-{v2}" if v2 != v else "")
    return f"{NAME[o]} {c}:{v}-{c2}:{v2}" if o == o2 else f"{NAME[o]} {c}:{v} - {NAME[o2]} {c2}:{v2}"


def vlabel(osis_ref):
    o, c, v = osis_ref.split(".")
    return f"{NAME[o]} {c}:{v}"


def text(vs):
    return " ".join(chapter("bsb", o, c)[v - 1] for (o, c, v) in vs if v <= len(chapter("bsb", o, c)))


def main():
    bridges = json.load(open(os.path.join(D, "prophecies_66_books.json"), encoding="utf-8"))
    extra = os.path.join(D, "appointed_times.json")
    if os.path.exists(extra):
        bridges += json.load(open(extra, encoding="utf-8"))["bridges"]
    covered = []
    for p in bridges:
        ot, _ = parse_refs(p["ot"]["ref"])
        nt, _ = parse_refs(p["nt"]["ref"])
        covered.append((set(ot), set(nt), p["id"]))

    # Every OT <-> NT link, keyed by (OT start verse, NT start verse); keep the stronger direction's votes.
    pairs = {}
    for b in BOOKS:
        for c in range(1, len(b["verses"]) + 1):
            for v, links in chapter("xref", b["osis"], c).items():
                src = (b["osis"], c, int(v))
                for target, votes in links:
                    if votes < MIN_VOTES:
                        continue
                    tv = expand(target)[:4]
                    if not tv or TESTAMENT[tv[0][0]] == TESTAMENT[b["osis"]]:
                        continue
                    if TESTAMENT[b["osis"]] == "OT":
                        ot, nt = [src], tv
                    else:
                        ot, nt = tv, [src]
                    key = (ot[0], nt[0])
                    if key not in pairs or pairs[key]["votes"] < votes:
                        pairs[key] = {"ot": ot, "nt": nt, "votes": votes}

    found = []
    for key, x in pairs.items():
        ot, nt = x["ot"], x["nt"]
        # Skip pairs inside a bridge, and New Testament passages a bridge already quotes (another Old Testament source
        # for the same words, such as Isaiah 44:3 beside Joel 2:28 in Acts 2:17, adds little).
        if any(set(nt) & cnt for (cot, cnt, pid) in covered):
            continue
        related = [pid for (cot, cnt, pid) in covered if set(ot) & cot]
        ot_t, nt_t = text(ot), text(nt)
        n, run = longest_run(words(ot_t), words(nt_t))
        f = formula_near(nt)
        score = math.log10(x["votes"]) + (2 if n >= 5 else 1 if n >= 4 else 0) + (1.5 if f else 0)
        found.append({"ot": label(ot), "nt": label(nt), "votes": x["votes"], "shared": {"words": n, "text": run},
                      "formula": f, "score": round(score, 2), "sameOtAs": related, "otText": ot_t, "ntText": nt_t})

    # One line per New Testament passage: the strongest Old Testament partner.
    best = {}
    for x in sorted(found, key=lambda y: -y["score"]):
        best.setdefault(x["nt"], x)
    ranked = sorted(best.values(), key=lambda y: -y["score"])
    quotes = [x for x in ranked if x["shared"]["words"] >= 5 or (x["formula"] and x["shared"]["words"] >= 3)]
    os.makedirs(OUT, exist_ok=True)
    json.dump({"about": __doc__.strip().split("\n")[0], "minVotes": MIN_VOTES, "candidates": ranked[:300]},
              open(os.path.join(OUT, "candidate_bridges.json"), "w", encoding="utf-8"), ensure_ascii=False, indent=1)

    lines = ["# Candidate bridges", "",
             "Old and New Testament verse pairs linked in OpenBible.info (at least %d votes) that no bridge covers yet, "
             "strongest evidence first. *Shared* is the longest run of identical BSB wording; *Scripture* means the New Testament "
             "passage refers to Scripture within two verses. Generated by `scripts/find_candidates.py`; nothing here is in the app." % MIN_VOTES, "",
             f"{len(found)} pairs not yet in a bridge; {len(ranked)} New Testament passages; {len(quotes)} look like quotations.", "",
             "## Likely quotations", ""]
    for i, x in enumerate(quotes[:60], 1):
        f = x["formula"]
        lines.append(f"{i}. **{x['ot']} → {x['nt']}** · {x['votes']} votes · shared {x['shared']['words']} words"
                     + (f" · Scripture ({vlabel(f['ref'])})" if f else "")
                     + (f" · same Old Testament verse as {', '.join(x['sameOtAs'])}" if x["sameOtAs"] else ""))
        lines.append(f"   - *{x['shared']['text']}*")
    lines += ["", "## Strong links without shared wording", "",
              "Often allusions or shared themes; worth a look for typology.", ""]
    other = [x for x in ranked if x not in quotes]
    for i, x in enumerate(other[:40], 1):
        lines.append(f"{i}. **{x['ot']} → {x['nt']}** · {x['votes']} votes" + (f" · same Old Testament verse as {', '.join(x['sameOtAs'])}" if x["sameOtAs"] else ""))
    open(os.path.join(OUT, "candidate_bridges.md"), "w", encoding="utf-8").write("\n".join(lines) + "\n")
    print(f"pairs {len(pairs)} | uncovered {len(found)} | NT passages {len(ranked)} | quotation-like {len(quotes)}")
    for x in quotes[:15]:
        print(f"  {x['score']:5} {x['ot']} -> {x['nt']} ({x['votes']}, {x['shared']['words']}w{', formula' if x['formula'] else ''})")


if __name__ == "__main__":
    main()
